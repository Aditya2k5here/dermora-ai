"""
Dermora AI - PDF case report.

Produces a single-page-per-case clinical summary: triage banner, the two
images (original and attention map), the full posterior, the ABCD workup and
the management block, over a legal disclaimer. Built with ReportLab platypus so
it paginates properly if the narrative runs long.
"""

from __future__ import annotations

import io
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (BaseDocTemplate, Frame, Image, KeepTogether,
                                PageBreak, PageTemplate, Paragraph, Spacer,
                                Table, TableStyle)

from .knowledge import LESIONS, RISK_TIERS

INK = colors.HexColor("#101820")
MUTED = colors.HexColor("#5b6b7a")
LINE = colors.HexColor("#d8e0e8")
ACCENT = colors.HexColor("#0e9f9f")
PAGE_W, PAGE_H = A4
MARGIN = 16 * mm


def _styles():
    base = getSampleStyleSheet()
    return {
        "h1": ParagraphStyle("h1", parent=base["Heading1"], fontName="Helvetica-Bold",
                             fontSize=16, leading=19, textColor=INK, spaceAfter=2),
        "h2": ParagraphStyle("h2", parent=base["Heading2"], fontName="Helvetica-Bold",
                             fontSize=10.5, leading=13, textColor=ACCENT,
                             spaceBefore=10, spaceAfter=4),
        "body": ParagraphStyle("body", parent=base["BodyText"], fontName="Helvetica",
                               fontSize=8.8, leading=12.4, textColor=INK,
                               alignment=TA_LEFT, spaceAfter=3),
        "small": ParagraphStyle("small", parent=base["BodyText"], fontName="Helvetica",
                                fontSize=7.4, leading=10, textColor=MUTED),
        "cell": ParagraphStyle("cell", parent=base["BodyText"], fontName="Helvetica",
                               fontSize=8, leading=10.5, textColor=INK, spaceAfter=0),
        "cellb": ParagraphStyle("cellb", parent=base["BodyText"], fontName="Helvetica-Bold",
                                fontSize=8, leading=10.5, textColor=INK, spaceAfter=0),
    }


def _chrome(canvas, doc):
    """Header rule and footer, drawn on every page."""
    canvas.saveState()
    canvas.setFillColor(INK)
    canvas.rect(0, PAGE_H - 13 * mm, PAGE_W, 13 * mm, stroke=0, fill=1)

    canvas.setFillColor(ACCENT)
    canvas.circle(MARGIN + 2.4 * mm, PAGE_H - 6.5 * mm, 2.4 * mm, stroke=0, fill=1)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 11)
    canvas.drawString(MARGIN + 7 * mm, PAGE_H - 8.1 * mm, "DERMORA AI")
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(colors.HexColor("#9fb3c8"))
    canvas.drawString(MARGIN + 33 * mm, PAGE_H - 8.1 * mm,
                      "Dermoscopic Lesion Analysis Report")
    canvas.drawRightString(PAGE_W - MARGIN, PAGE_H - 8.1 * mm,
                           "DECISION SUPPORT - NOT A DIAGNOSIS")

    canvas.setStrokeColor(LINE)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 13 * mm, PAGE_W - MARGIN, 13 * mm)
    canvas.setFont("Helvetica", 7)
    canvas.setFillColor(MUTED)
    canvas.drawString(MARGIN, 9 * mm,
                      "Generated by Dermora AI. Output is probabilistic and must be "
                      "interpreted by a qualified clinician.")
    canvas.drawRightString(PAGE_W - MARGIN, 9 * mm, f"Page {canvas.getPageNumber()}")
    canvas.restoreState()


def _tint(hex_color: str, strength: float = 0.14) -> colors.Color:
    """Blend a colour towards white. ReportLab has no alpha in table fills."""
    c = colors.HexColor(hex_color)
    return colors.Color(1 - (1 - c.red) * strength,
                        1 - (1 - c.green) * strength,
                        1 - (1 - c.blue) * strength)


def _bar(fraction: float, color: colors.Color, width: float = 34 * mm) -> Table:
    """A horizontal probability bar rendered as a two-cell table."""
    fraction = max(0.0, min(1.0, float(fraction)))
    filled = max(0.4, width * fraction)
    t = Table([[""]], colWidths=[filled], rowHeights=[3.4 * mm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), color),
        ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    outer = Table([[t]], colWidths=[width])
    outer.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#eef2f6")),
        ("ALIGN", (0, 0), (-1, -1), "LEFT"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 1), ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
    ]))
    return outer


def build_report(case: dict, image_bytes: dict[str, bytes]) -> bytes:
    """
    `case` is the analysis dict served by the API. `image_bytes` maps
    'original' / 'attention' / 'outline' to encoded PNG/JPEG bytes.
    """
    st = _styles()
    buf = io.BytesIO()

    doc = BaseDocTemplate(buf, pagesize=A4,
                          leftMargin=MARGIN, rightMargin=MARGIN,
                          topMargin=17 * mm, bottomMargin=16 * mm,
                          title=f"Dermora AI Report {case.get('case_id', '')}",
                          author="Dermora AI")
    frame = Frame(MARGIN, 16 * mm, PAGE_W - 2 * MARGIN, PAGE_H - 33 * mm, id="body")
    doc.addPageTemplates([PageTemplate(id="main", frames=[frame], onPage=_chrome)])

    pred = case["prediction"]
    triage = case["triage"]
    top_code = pred["top_class"]
    rec = LESIONS[top_code]
    risk_hex = RISK_TIERS[triage["risk"]]["color"]
    content_w = PAGE_W - 2 * MARGIN

    story: list = []

    # -- case identity ----------------------------------------------------
    story.append(Paragraph(f"{rec['full_name']} <font color='#5b6b7a'>({top_code})</font>", st["h1"]))
    meta = (f"Case {case.get('case_id', '-')} &nbsp;|&nbsp; Source: {case.get('filename', '-')} "
            f"&nbsp;|&nbsp; Analysed {case.get('timestamp', datetime.now().isoformat(timespec='seconds'))} "
            f"&nbsp;|&nbsp; {pred['views']}-view TTA &nbsp;|&nbsp; {pred['inference_ms']:.0f} ms")
    story.append(Paragraph(meta, st["small"]))
    story.append(Spacer(1, 5 * mm))

    # -- triage banner ----------------------------------------------------
    banner = Table([[
        Paragraph(f"<font color='white' size='11'><b>{triage['band']}</b></font><br/>"
                  f"<font color='white' size='8.5'>{triage['headline']}</font>", st["cell"]),
        Paragraph(f"<font color='white' size='16'><b>{pred['confidence'] * 100:.1f}%</b></font><br/>"
                  f"<font color='#dbe7ef' size='7'>model confidence</font>", st["cell"]),
        Paragraph(f"<font color='white' size='16'><b>{case['concern'] * 100:.1f}%</b></font><br/>"
                  f"<font color='#dbe7ef' size='7'>malignant + pre-malignant</font>", st["cell"]),
    ]], colWidths=[content_w * 0.56, content_w * 0.22, content_w * 0.22])
    banner.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(risk_hex)),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 8), ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 7), ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
    ]))
    story.append(banner)
    story.append(Spacer(1, 2 * mm))
    story.append(Paragraph(triage["detail"], st["body"]))

    # -- imagery ----------------------------------------------------------
    story.append(Paragraph("IMAGING", st["h2"]))
    cells, labels = [], []
    for key, label in (("original", "Submitted image"),
                       ("attention", "Eigen-CAM attention"),
                       ("outline", "Segmented lesion")):
        data = image_bytes.get(key)
        if not data:
            continue
        img = Image(io.BytesIO(data))
        ratio = img.imageHeight / float(img.imageWidth)
        img.drawWidth = (content_w - 8 * mm) / 3.0
        img.drawHeight = img.drawWidth * ratio
        cells.append(img)
        labels.append(Paragraph(f"<font size='7' color='#5b6b7a'>{label}</font>", st["small"]))

    if cells:
        grid = Table([cells, labels], colWidths=[(content_w) / len(cells)] * len(cells))
        grid.setStyle(TableStyle([
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
            ("VALIGN", (0, 0), (-1, 0), "TOP"),
            ("TOPPADDING", (0, 1), (-1, 1), 2),
            ("LEFTPADDING", (0, 0), (-1, -1), 2), ("RIGHTPADDING", (0, 0), (-1, -1), 2),
        ]))
        story.append(grid)

    att = case.get("attention", {})
    if att.get("available"):
        story.append(Paragraph(
            f"<font size='7.4' color='#5b6b7a'>Attention concentration "
            f"{att['concentration'] * 100:.0f}% of saliency mass in the top decile. "
            f"{att['interpretation']}</font>", st["small"]))

    # -- posterior --------------------------------------------------------
    story.append(Paragraph("CLASS POSTERIOR", st["h2"]))
    rows = [[Paragraph("<b>Class</b>", st["cellb"]), Paragraph("<b>Diagnosis</b>", st["cellb"]),
             Paragraph("<b>Category</b>", st["cellb"]), "", Paragraph("<b>P</b>", st["cellb"])]]
    for item in pred["ranked"]:
        info = LESIONS[item["code"]]
        rows.append([
            Paragraph(f"<b>{item['code']}</b>", st["cell"]),
            Paragraph(info["name"], st["cell"]),
            Paragraph(info["category"], st["cell"]),
            _bar(item["prob"], colors.HexColor(RISK_TIERS[info["risk"]]["color"])),
            Paragraph(f"<b>{item['prob'] * 100:.1f}%</b>", st["cell"]),
        ])
    tbl = Table(rows, colWidths=[content_w * 0.10, content_w * 0.34, content_w * 0.16,
                                 content_w * 0.26, content_w * 0.14])
    tbl.setStyle(TableStyle([
        ("LINEBELOW", (0, 0), (-1, 0), 0.7, LINE),
        ("LINEBELOW", (0, 1), (-1, -2), 0.25, colors.HexColor("#eef2f6")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BACKGROUND", (0, 1), (-1, 1), colors.HexColor("#f4f8fb")),
        ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("ALIGN", (4, 0), (4, -1), "RIGHT"),
    ]))
    story.append(tbl)
    story.append(Spacer(1, 1.5 * mm))
    story.append(Paragraph(
        f"<font size='7.4' color='#5b6b7a'>Top-two margin {pred['margin'] * 100:.1f} pts &nbsp;|&nbsp; "
        f"normalised entropy {pred['entropy']:.2f} &nbsp;|&nbsp; TTA agreement "
        f"{pred['tta_agreement'] * 100:.0f}% &nbsp;|&nbsp; peak detector score "
        f"{pred['detector_score']:.3f}</font>", st["small"]))

    # -- interpretation ---------------------------------------------------
    story.append(Paragraph("INTERPRETATION", st["h2"]))
    story.append(Paragraph(case["narrative"], st["body"]))

    feats = "".join(f"&bull; {f}<br/>" for f in rec["dermoscopy"])
    story.append(Paragraph(
        f"<b>Expected dermoscopic features for {rec['name']}:</b><br/>{feats}", st["body"]))

    # -- morphometry ------------------------------------------------------
    morph = case.get("morphology", {})
    if morph.get("available"):
        abcd = morph["abcd"]
        morph_block: list = [Paragraph("MORPHOMETRY - ABCD RULE OF DERMOSCOPY (STOLZ)", st["h2"])]
        comp = abcd["components"]
        mrows = [
            [Paragraph("<b>Axis</b>", st["cellb"]), Paragraph("<b>Measurement</b>", st["cellb"]),
             Paragraph("<b>Score</b>", st["cellb"]), Paragraph("<b>Weight</b>", st["cellb"])],
            [Paragraph("A - Asymmetry", st["cell"]),
             Paragraph(f"{morph['asymmetry']['index'] * 100:.1f}% non-overlap under axial reflection", st["cell"]),
             Paragraph(f"{comp['A']} / 2", st["cell"]), Paragraph("1.3", st["cell"])],
            [Paragraph("B - Border", st["cell"]),
             Paragraph(f"{comp['B']} of 8 sectors with abrupt cut-off; compactness "
                       f"{morph['border']['compactness']:.2f}", st["cell"]),
             Paragraph(f"{comp['B']} / 8", st["cell"]), Paragraph("0.1", st["cell"])],
            [Paragraph("C - Colour", st["cell"]),
             Paragraph(", ".join(morph["color"]["present"]) or "single colour", st["cell"]),
             Paragraph(f"{comp['C']} / 6", st["cell"]), Paragraph("0.5", st["cell"])],
            [Paragraph("D - Structures", st["cell"]),
             Paragraph(f"{morph['structures']['clusters']} distinct colour-texture regions "
                       f"(approximation)", st["cell"]),
             Paragraph(f"{comp['D']} / 5", st["cell"]), Paragraph("0.5", st["cell"])],
        ]
        mt = Table(mrows, colWidths=[content_w * 0.20, content_w * 0.52,
                                     content_w * 0.16, content_w * 0.12])
        mt.setStyle(TableStyle([
            ("LINEBELOW", (0, 0), (-1, 0), 0.7, LINE),
            ("LINEBELOW", (0, 1), (-1, -2), 0.25, colors.HexColor("#eef2f6")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]))
        morph_block.append(mt)

        band_color = {"BENIGN": "#2aa06a", "SUSPICIOUS": "#c98a00", "HIGH": "#ff3b5c"}[abcd["band"]]
        tds = Table([[Paragraph(
            f"<font size='9'><b>Total Dermoscopy Score {abcd['tds']}</b> &nbsp;-&nbsp; "
            f"{abcd['verdict']}</font>", st["cell"])]], colWidths=[content_w])
        tds.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), _tint(band_color)),
            ("LINEBEFORE", (0, 0), (0, -1), 2.4, colors.HexColor(band_color)),
            ("LEFTPADDING", (0, 0), (-1, -1), 7),
            ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]))
        morph_block += [Spacer(1, 2 * mm), tds, Spacer(1, 1.5 * mm), Paragraph(
            f"<font size='7.4' color='#5b6b7a'>Lesion diameter {morph['geometry']['diameter_px']:.0f} px "
            f"({morph['geometry']['frame_fraction'] * 100:.0f}% of frame width). "
            f"{morph['geometry']['note']} {morph['evolution_note']}</font>", st["small"])]
        story.append(KeepTogether(morph_block))

    # -- management -------------------------------------------------------
    story.append(Paragraph("SUGGESTED MANAGEMENT", st["h2"]))
    story.append(Paragraph(rec["management"], st["body"]))
    story.append(Paragraph(f"<b>Urgency:</b> {rec['urgency']}", st["body"]))

    # -- quality ----------------------------------------------------------
    q = case.get("quality", {})
    if q:
        flags = " ".join(f"&bull; {f}" for f in q.get("flags", [])) or "No quality issues detected."
        story.append(Paragraph("IMAGE QUALITY", st["h2"]))
        story.append(Paragraph(
            f"Quality index {q.get('score', 0):.0f}/100 &nbsp;|&nbsp; focus {q.get('focus', 0):.0f} "
            f"&nbsp;|&nbsp; resolution {q.get('resolution', ['?', '?'])[0]}x"
            f"{q.get('resolution', ['?', '?'])[1]} &nbsp;|&nbsp; {flags}", st["small"]))

    # -- disclaimer -------------------------------------------------------
    story.append(Spacer(1, 4 * mm))
    disc = Table([[Paragraph(
        "<font size='7.2'><b>IMPORTANT.</b> Dermora AI is an academic decision-support "
        "prototype. The underlying model was trained on the ISIC 2018 Task 3 (HAM10000) "
        "dataset, which over-represents fair skin types and does not cover every lesion "
        "class encountered in practice. Output is a probability distribution, not a "
        "diagnosis, and carries no regulatory clearance for clinical use. It must not be "
        "used to make or defer treatment decisions. Any lesion of concern requires "
        "in-person assessment by a qualified clinician, and histopathology remains the "
        "diagnostic standard.</font>", st["small"])]], colWidths=[content_w])
    disc.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fff6f0")),
        ("LINEBEFORE", (0, 0), (0, -1), 2.4, colors.HexColor("#ff7a45")),
        ("LEFTPADDING", (0, 0), (-1, -1), 7), ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(KeepTogether(disc))

    doc.build(story)
    return buf.getvalue()
